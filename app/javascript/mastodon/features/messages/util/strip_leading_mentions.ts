// @_longwhile custom feature / 한참(longwhile) 제작 기능 — DM 채팅
//   본문 앞에 붙은 수신자 핸들을 뗀다.
//
//   DM 은 전용 전송 경로가 없다. 마스토돈은 direct 글을 **본문에 멘션된 사람**
//   에게 배달하므로, 보낼 때 핸들을 실제로 본문 앞에 넣고 화면에서는 그것을
//   지워서 보여준다 (FR-13, api/dm_rooms.ts).
//
//   그래서 원문을 입력창으로 되돌릴 때 — "수정", "지우고 다시 쓰기" — 그 핸들을
//   다시 떼야 한다. 그대로 넣으면 사용자가 쓴 적 없는 핸들이 갑자기 나타나고,
//   그 상태로 저장하면 핸들이 두 벌이 된다(전송 시 방 참여자로 다시 붙이므로).

// 줄바꿈은 먹지 않는다. `\s` 를 쓰면 첫 줄이 핸들뿐이고 본문이 다음 줄부터인
// 메시지에서 그 줄바꿈까지 삼켜 문단이 붙어버린다.
//
// `@사용자` 와 `@사용자@도메인` 을 모두 받는다. 연합이 꺼져 있어도 예전에 들어온
// 글에는 도메인이 붙어 있을 수 있다.
const LEADING_MENTIONS = /^(?:@[^\s@]+(?:@[^\s]+)?[ \t]+)*/;

export const stripLeadingMentions = (text: string) =>
  text.replace(LEADING_MENTIONS, '');
